    before = [0.57, 0.79]     # raw cross-window labels (≈chance / pooled LOWO)
    after = [0.994, 1.00]     # swap-corrected (LOSO AUC 0.994 / LOWO 1.00)
    notes_before = ["raw labels\n(ARI ≈ 0)", "pooled\nLOWO 0.83/0.75"]
    notes_after = ["LOSO\nAUC 0.994", "LOWO 1.00\n(AUC 0.982)"]

